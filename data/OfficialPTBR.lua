local function ApplyGlobalTable(source)
    local applied = 0
    for key, value in pairs(source or {}) do
        if type(value) == "string" and type(rawget(_G, key)) == "string" then
            rawset(_G, key, value)
            applied = applied + 1
        end
    end
    return applied
end

function A.ApplyOfficialDisplayGlobals(options)
    if type(options) ~= "table" then return 0 end
    local applied = 0
    if options.items then applied = applied + ApplyGlobalTable(A.OfficialItemGlobals) end
    if options.ui then applied = applied + ApplyGlobalTable(A.OfficialStatGlobals) end
    return applied
end

